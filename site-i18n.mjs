let activeLocale = 'en';

export function getTranslation(key, locale = activeLocale, values = {}) {
  const language = translations[locale] ? locale : 'en';
  const template = translations[language][key] || translations.en[key] || key;
  return template.replace(/\{(\w+)\}/g, (_match, name) => String(values[name] ?? `{${name}}`));
}

function preferredLocale() {
  try {
    const stored = localStorage.getItem('houselearning-site-locale');
    if (translations[stored]) return stored;
  } catch (_error) {
    // Use the browser language when storage is unavailable.
  }
  const browser = (navigator.languages || [navigator.language || 'en']).join(',').toLowerCase();
  if (browser.includes('es')) return 'es';
  if (browser.includes('tr')) return 'tr';
  return 'en';
}

function applyLocale(locale) {
  activeLocale = translations[locale] ? locale : 'en';
  document.documentElement.lang = activeLocale;
  document.querySelectorAll('[data-site-i18n]').forEach(element => {
    element.textContent = getTranslation(element.dataset.siteI18n, activeLocale, {
      grade: element.dataset.siteI18nGrade
    });
  });
  document.querySelectorAll('[data-site-i18n-placeholder]').forEach(element => {
    element.setAttribute('placeholder', getTranslation(element.dataset.siteI18nPlaceholder));
  });
  document.querySelectorAll('[data-site-i18n-title]').forEach(element => {
    element.textContent = getTranslation(element.dataset.siteI18nTitle);
  });
  document.dispatchEvent(new CustomEvent('houselearning:localechange', { detail: { locale: activeLocale } }));
}

function initializeLocaleSelector() {
  const selectorWrap = document.createElement('div');
  selectorWrap.className = 'hl-language-control';
  const label = document.createElement('label');
  label.htmlFor = 'hl-site-language';
  label.textContent = getTranslation('language', activeLocale);
  const selector = document.createElement('select');
  selector.id = 'hl-site-language';
  selector.setAttribute('aria-label', getTranslation('language', activeLocale));
  for (const locale of ['en', 'es', 'tr']) {
    const option = document.createElement('option');
    option.value = locale;
    option.textContent = getTranslation(`language.${locale === 'en' ? 'english' : locale === 'es' ? 'spanish' : 'turkish'}`, activeLocale);
    selector.appendChild(option);
  }
  selector.value = activeLocale;
  selector.addEventListener('change', () => {
    activeLocale = selector.value;
    try {
      localStorage.setItem('houselearning-site-locale', activeLocale);
    } catch (_error) {
      // The selected locale still applies for this page view.
    }
    label.textContent = getTranslation('language', activeLocale);
    selector.setAttribute('aria-label', getTranslation('language', activeLocale));
    Array.from(selector.options).forEach(option => {
      const optionKey = `language.${option.value === 'en' ? 'english' : option.value === 'es' ? 'spanish' : 'turkish'}`;
      option.textContent = getTranslation(optionKey, activeLocale);
    });
    applyLocale(activeLocale);
  });
  selectorWrap.append(label, selector);
  document.body.appendChild(selectorWrap);
  applyLocale(activeLocale);
}

if (typeof document !== 'undefined') {
  activeLocale = preferredLocale();
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initializeLocaleSelector, { once: true });
  } else {
    initializeLocaleSelector();
  }
}